const generateCertificates = (count: number, startNo: number, hasManual = false): Certificate[] => {
  const certs: Certificate[] = [];
  for (let i = 0; i < count; i++) {
    const certNo = `GC-2026-${String(startNo + i).padStart(4, '0')}`;
    certs.push({
      id: `cert-${startNo + i}`,
      certNo,
      power: Math.round((Math.random() * 50 + 50) * 100) / 100,
      isManualSupply: false,
    });
  }
  if (hasManual) {
    certs.push({
      id: 'cert-manual-001',
      certNo: 'GC-2026-MANUAL-001',
      power: 125.5,
      scanUrl: '/certificate.svg',
      isManualSupply: true,
      suppliedBy: '周顾问',
      supplyTime: '2026-06-09 10:30:00',
    });
  }
  return certs;
};

